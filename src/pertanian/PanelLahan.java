        private void siapkan() {
        txtIdLahan.setEditable(false);
        Util.isiCombo(cmPetani, "SELECT id_petani, nama_petani FROM petani ORDER BY nama_petani", false);
        btnSimpan.addActionListener(e -> simpan());
        btnEdit.addActionListener(e -> ubah());
        btnHapus.addActionListener(e -> hapus());
        tabelLahan.getSelectionModel().addListSelectionListener(e -> {
            if (!e.getValueIsAdjusting()) {
                isiForm();
            }
        });
        muatData();
    }

    private void muatData() {
        Util.isiTabel(tabelLahan, "SELECT id_lahan, nama_lahan, luas_lahan, id_petani FROM lahan ORDER BY id_lahan");
    }

    private void bersihkan() {
        txtIdLahan.setText("");
        txtNamaLahan.setText("");
        txtLuasLahan.setText("");
        Util.pilihCombo(cmPetani, "");
        tabelLahan.clearSelection();
    }

    private void isiForm() {
        int b = tabelLahan.getSelectedRow();
        if (b < 0) {
            return;
        }
        txtIdLahan.setText(Util.ambil(tabelLahan, b, 0));
        txtNamaLahan.setText(Util.ambil(tabelLahan, b, 1));
        txtLuasLahan.setText(Util.ambil(tabelLahan, b, 2));
        Util.pilihCombo(cmPetani, Util.ambil(tabelLahan, b, 3));
    }

    private void simpan() {
        try {
            String nama = Util.wajib(txtNamaLahan.getText(), "Nama lahan");
            double luas = Util.desimal(txtLuasLahan.getText(), "Luas lahan");
            Integer idPetani = Util.idCombo(cmPetani);
            if (idPetani == null) {
                throw new IllegalArgumentException("Petani belum dipilih.");
            }
            if (Util.eksekusi("INSERT INTO lahan (nama_lahan, luas_lahan, id_petani) VALUES (?, ?, ?)", nama, luas, idPetani)) {
                Util.pesan("Data berhasil disimpan.");
                muatData();
                bersihkan();
            }
        } catch (IllegalArgumentException ex) {
            Util.pesan(ex.getMessage());
        }
    }

    private void ubah() {
        if (!Util.adaPilihan(txtIdLahan.getText())) {
            return;
        }
        try {
            int id = Util.angka(txtIdLahan.getText(), "ID Lahan");
            String nama = Util.wajib(txtNamaLahan.getText(), "Nama lahan");
            double luas = Util.desimal(txtLuasLahan.getText(), "Luas lahan");
            Integer idPetani = Util.idCombo(cmPetani);
            if (idPetani == null) {
                throw new IllegalArgumentException("Petani belum dipilih.");
            }
            if (Util.eksekusi("UPDATE lahan SET nama_lahan = ?, luas_lahan = ?, id_petani = ? WHERE id_lahan = ?", nama, luas, idPetani, id)) {
                Util.pesan("Data berhasil diubah.");
                muatData();
                bersihkan();
            }
        } catch (IllegalArgumentException ex) {
            Util.pesan(ex.getMessage());
        }
    }
 
    private void hapus() {
        if (!Util.adaPilihan(txtIdLahan.getText())) {
            return;
        }
        if (Util.konfirmasi("Hapus data lahan ini?")
                && Util.eksekusi("DELETE FROM lahan WHERE id_lahan = ?", Integer.parseInt(txtIdLahan.getText().trim()))) {
            Util.pesan("Data berhasil dihapus.");
            muatData();
            bersihkan();
        }
    }

