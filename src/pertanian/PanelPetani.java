    private void siapkan() {
        txtIdPetani.setEditable(false);
        btnSimpan.addActionListener(e -> simpan());
        btnEdit.addActionListener(e -> ubah());
        btnHapus.addActionListener(e -> hapus());
        tabelPetani.getSelectionModel().addListSelectionListener(e -> {
            if (!e.getValueIsAdjusting()) {
                isiForm();
            }
        });
        muatData();
    }
 
    private void muatData() {
        Util.isiTabel(tabelPetani, "SELECT id_petani, nama_petani, alamat_petani, no_hp FROM petani ORDER BY id_petani");
    }
 
    private void bersihkan() {
        txtIdPetani.setText("");
        txtNamaPetani.setText("");
        txtAlamatPetani.setText("");
        txtNoHp.setText("");
        tabelPetani.clearSelection();
    }
 
    private void isiForm() {
        int b = tabelPetani.getSelectedRow();
        if (b < 0) {
            return;
        }
        txtIdPetani.setText(Util.ambil(tabelPetani, b, 0));
        txtNamaPetani.setText(Util.ambil(tabelPetani, b, 1));
        txtAlamatPetani.setText(Util.ambil(tabelPetani, b, 2));
        txtNoHp.setText(Util.ambil(tabelPetani, b, 3));
    }
 
    private void simpan() {
        try {
            String nama = Util.wajib(txtNamaPetani.getText(), "Nama petani");
            String alamat = txtAlamatPetani.getText().trim();
            String hp = txtNoHp.getText().trim();
            if (Util.eksekusi("INSERT INTO petani (nama_petani, alamat_petani, no_hp) VALUES (?, ?, ?)", nama, alamat, hp)) {
                Util.pesan("Data berhasil disimpan.");
                muatData();
                bersihkan();
            }
        } catch (IllegalArgumentException ex) {
            Util.pesan(ex.getMessage());
        }
    }
 
    private void ubah() {
        if (!Util.adaPilihan(txtIdPetani.getText())) {
            return;
        }
        try {
            int id = Util.angka(txtIdPetani.getText(), "ID Petani");
            String nama = Util.wajib(txtNamaPetani.getText(), "Nama petani");
            String alamat = txtAlamatPetani.getText().trim();
            String hp = txtNoHp.getText().trim();
            if (Util.eksekusi("UPDATE petani SET nama_petani = ?, alamat_petani = ?, no_hp = ? WHERE id_petani = ?", nama, alamat, hp, id)) {
                Util.pesan("Data berhasil diubah.");
                muatData();
                bersihkan();
            }
        } catch (IllegalArgumentException ex) {
            Util.pesan(ex.getMessage());
        }
    }
 
    private void hapus() {
        if (!Util.adaPilihan(txtIdPetani.getText())) {
            return;
        }
        if (Util.konfirmasi("Hapus data petani ini?")
                && Util.eksekusi("DELETE FROM petani WHERE id_petani = ?", Integer.parseInt(txtIdPetani.getText().trim()))) {
            Util.pesan("Data berhasil dihapus.");
            muatData();
            bersihkan();
        }
    }

