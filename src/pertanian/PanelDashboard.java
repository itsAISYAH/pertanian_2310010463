    private void muatData() {
        hasilPetani.setText(String.valueOf(Util.hitung("SELECT COUNT(*) FROM petani")));
        hasilLahan.setText(String.valueOf(Util.hitung("SELECT COUNT(*) FROM lahan")));
        hasilTanamanAktif.setText(String.valueOf(Util.hitung(
                "SELECT COUNT(*) FROM tanaman WHERE id_tanaman IN (SELECT id_tanaman FROM penanaman) "
                + "AND id_tanaman NOT IN (SELECT id_tanaman FROM panen)")));
        hasilJadwalMingguIni.setText(String.valueOf(
                Util.hitung("SELECT COUNT(*) FROM jadwal_pemupukan WHERE YEARWEEK(tanggal, 1) = YEARWEEK(CURDATE(), 1)")
                + Util.hitung("SELECT COUNT(*) FROM jadwal_obat_hama WHERE YEARWEEK(tanggal, 1) = YEARWEEK(CURDATE(), 1)")));
        hasilPanenBulanIni.setText(String.valueOf(Util.hitung(
                "SELECT COUNT(*) FROM panen WHERE MONTH(tanggal) = MONTH(CURDATE()) AND YEAR(tanggal) = YEAR(CURDATE())")));
        hasilStokMenipis.setText(String.valueOf(Util.hitung(
                "SELECT COUNT(*) FROM persediaan_stok WHERE jumlah_barang < 10")));
    }

