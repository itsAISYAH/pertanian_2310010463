    private void siapkan() {
        txtIdBarang.setEditable(false);
        btnSimpan.addActionListener(e -> simpan());
        btnEdit.addActionListener(e -> ubah());
        btnHapus.addActionListener(e -> hapus());
        tabelStok.getSelectionModel().addListSelectionListener(e -> {
            if (!e.getValueIsAdjusting()) {
                isiForm();
            }
        });
        muatData();
    }
 
    private void muatData() {
        Util.isiTabel(tabelStok, "SELECT id_barang, nama_barang, jumlah_barang FROM persediaan_stok ORDER BY id_barang");
    }
 
    private void bersihkan() {
        txtIdBarang.setText("");
        txtNamaBarang.setText("");
        txtJumlahBarang.setText("");
        tabelStok.clearSelection();
    }
 
    private void isiForm() {
        int b = tabelStok.getSelectedRow();
        if (b < 0) {
            return;
        }
        txtIdBarang.setText(Util.ambil(tabelStok, b, 0));
        txtNamaBarang.setText(Util.ambil(tabelStok, b, 1));
        txtJumlahBarang.setText(Util.ambil(tabelStok, b, 2));
    }
 
    private void simpan() {
        try {
            String nama = Util.wajib(txtNamaBarang.getText(), "Nama barang");
            int jumlah = Util.angka(txtJumlahBarang.getText(), "Jumlah barang");
            if (jumlah < 0) {
                throw new IllegalArgumentException("Jumlah barang tidak boleh negatif.");
            }
            if (Util.eksekusi("INSERT INTO persediaan_stok (nama_barang, jumlah_barang) VALUES (?, ?)", nama, jumlah)) {
                Util.pesan("Data berhasil disimpan.");
                muatData();
                bersihkan();
            }
        } catch (IllegalArgumentException ex) {
            Util.pesan(ex.getMessage());
        }
    }
 
    private void ubah() {
        if (!Util.adaPilihan(txtIdBarang.getText())) {
            return;
        }
        try {
            int id = Util.angka(txtIdBarang.getText(), "ID Barang");
            String nama = Util.wajib(txtNamaBarang.getText(), "Nama barang");
            int jumlah = Util.angka(txtJumlahBarang.getText(), "Jumlah barang");
            if (jumlah < 0) {
                throw new IllegalArgumentException("Jumlah barang tidak boleh negatif.");
            }
            if (Util.eksekusi("UPDATE persediaan_stok SET nama_barang = ?, jumlah_barang = ? WHERE id_barang = ?", nama, jumlah, id)) {
                Util.pesan("Data berhasil diubah.");
                muatData();
                bersihkan();
            }
        } catch (IllegalArgumentException ex) {
            Util.pesan(ex.getMessage());
        }
    }
 
    private void hapus() {
        if (!Util.adaPilihan(txtIdBarang.getText())) {
            return;
        }
        if (Util.konfirmasi("Hapus barang ini dari persediaan stok?")
                && Util.eksekusi("DELETE FROM persediaan_stok WHERE id_barang = ?", Integer.parseInt(txtIdBarang.getText().trim()))) {
            Util.pesan("Data berhasil dihapus.");
            muatData();
            bersihkan();
        }
    }

