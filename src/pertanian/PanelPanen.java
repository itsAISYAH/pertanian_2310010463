        private void siapkan() {
        txtIdPanen.setEditable(false);
        Util.isiCombo(cmTanaman, "SELECT id_tanaman, nama_tanaman FROM tanaman ORDER BY nama_tanaman", false);
        btnSimpan.addActionListener(e -> simpan());
        btnEdit.addActionListener(e -> ubah());
        btnHapus.addActionListener(e -> hapus());
        tabelPanen.getSelectionModel().addListSelectionListener(e -> {
            if (!e.getValueIsAdjusting()) {
                isiForm();
            }
        });
        muatData();
    }

    private void muatData() {
        Util.isiTabel(tabelPanen, "SELECT id_panen, id_tanaman, nama_panen, jumlah_panen, tanggal, waktu FROM panen ORDER BY tanggal DESC, id_panen DESC");
    }

    private void bersihkan() {
        txtIdPanen.setText("");
        Util.pilihCombo(cmTanaman, "");
        txtNamaPanen.setText("");
        txtJumlahPanen.setText("");
        jDateChooser1.setDate(null);
        txtWaktu.setText("");
        tabelPanen.clearSelection();
    }

    private void isiForm() {
        int b = tabelPanen.getSelectedRow();
        if (b < 0) {
            return;
        }
        txtIdPanen.setText(Util.ambil(tabelPanen, b, 0));
        Util.pilihCombo(cmTanaman, Util.ambil(tabelPanen, b, 1));
        txtNamaPanen.setText(Util.ambil(tabelPanen, b, 2));
        txtJumlahPanen.setText(Util.ambil(tabelPanen, b, 3));
        jDateChooser1.setDate(Util.keTanggal(Util.ambil(tabelPanen, b, 4)));
        txtWaktu.setText(Util.ambil(tabelPanen, b, 5));
    }

    private void simpan() {
        try {
            Integer idTanaman = Util.idCombo(cmTanaman);
            if (idTanaman == null) {
                throw new IllegalArgumentException("Tanaman belum dipilih.");
            }
            String nama = Util.wajib(txtNamaPanen.getText(), "Nama panen");
            int jumlah = Util.angka(txtJumlahPanen.getText(), "Jumlah panen");
            java.sql.Date tgl = Util.tanggal(jDateChooser1.getDate());
            java.sql.Time wkt = Util.waktu(txtWaktu.getText());
            if (Util.eksekusi("INSERT INTO panen (id_tanaman, nama_panen, jumlah_panen, tanggal, waktu) VALUES (?, ?, ?, ?, ?)",
                    idTanaman, nama, jumlah, tgl, wkt)) {
                Util.pesan("Data berhasil disimpan.");
                muatData();
                bersihkan();
            }
        } catch (IllegalArgumentException ex) {
            Util.pesan(ex.getMessage());
        }
    }

    private void ubah() {
        if (!Util.adaPilihan(txtIdPanen.getText())) {
            return;
        }
        try {
            int id = Util.angka(txtIdPanen.getText(), "ID Panen");
            Integer idTanaman = Util.idCombo(cmTanaman);
            if (idTanaman == null) {
                throw new IllegalArgumentException("Tanaman belum dipilih.");
            }
            String nama = Util.wajib(txtNamaPanen.getText(), "Nama panen");
            int jumlah = Util.angka(txtJumlahPanen.getText(), "Jumlah panen");
            java.sql.Date tgl = Util.tanggal(jDateChooser1.getDate());
            java.sql.Time wkt = Util.waktu(txtWaktu.getText());
            if (Util.eksekusi("UPDATE panen SET id_tanaman = ?, nama_panen = ?, jumlah_panen = ?, tanggal = ?, waktu = ? WHERE id_panen = ?",
                    idTanaman, nama, jumlah, tgl, wkt, id)) {
                Util.pesan("Data berhasil diubah.");
                muatData();
                bersihkan();
            }
        } catch (IllegalArgumentException ex) {
            Util.pesan(ex.getMessage());
        }
    }
 
    private void hapus() {
        if (!Util.adaPilihan(txtIdPanen.getText())) {
            return;
        }
        if (Util.konfirmasi("Hapus data panen ini?")
                && Util.eksekusi("DELETE FROM panen WHERE id_panen = ?", Integer.parseInt(txtIdPanen.getText().trim()))) {
            Util.pesan("Data berhasil dihapus.");
            muatData();
            bersihkan();
        }
    }

