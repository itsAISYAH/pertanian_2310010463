        private void siapkan() {
        txtIdTanaman.setEditable(false);
        Util.isiCombo(cmLahan, "SELECT id_lahan, nama_lahan FROM lahan ORDER BY nama_lahan", false);
        btnSimpan.addActionListener(e -> simpan());
        btnEdit.addActionListener(e -> ubah());
        btnHapus.addActionListener(e -> hapus());
        jTable1.getSelectionModel().addListSelectionListener(e -> {
            if (!e.getValueIsAdjusting()) {
                isiForm();
            }
        });
        muatData();
    }

    private void muatData() {
        Util.isiTabel(jTable1, "SELECT id_tanaman, nama_tanaman, id_lahan FROM tanaman ORDER BY id_tanaman");
    }

    private void bersihkan() {
        txtIdTanaman.setText("");
        txtNamaTanaman.setText("");
        Util.pilihCombo(cmLahan, "");
        jTable1.clearSelection();
    }

    private void isiForm() {
        int b = jTable1.getSelectedRow();
        if (b < 0) {
            return;
        }
        txtIdTanaman.setText(Util.ambil(jTable1, b, 0));
        txtNamaTanaman.setText(Util.ambil(jTable1, b, 1));
        Util.pilihCombo(cmLahan, Util.ambil(jTable1, b, 2));
    }

    private void simpan() {
        try {
            String nama = Util.wajib(txtNamaTanaman.getText(), "Nama tanaman");
            Integer idLahan = Util.idCombo(cmLahan);
            if (idLahan == null) {
                throw new IllegalArgumentException("Lahan belum dipilih.");
            }
            if (Util.eksekusi("INSERT INTO tanaman (nama_tanaman, id_lahan) VALUES (?, ?)", nama, idLahan)) {
                Util.pesan("Data berhasil disimpan.");
                muatData();
                bersihkan();
            }
        } catch (IllegalArgumentException ex) {
            Util.pesan(ex.getMessage());
        }
    }

    private void ubah() {
        if (!Util.adaPilihan(txtIdTanaman.getText())) {
            return;
        }
        try {
            int id = Util.angka(txtIdTanaman.getText(), "ID Tanaman");
            String nama = Util.wajib(txtNamaTanaman.getText(), "Nama tanaman");
            Integer idLahan = Util.idCombo(cmLahan);
            if (idLahan == null) {
                throw new IllegalArgumentException("Lahan belum dipilih.");
            }
            if (Util.eksekusi("UPDATE tanaman SET nama_tanaman = ?, id_lahan = ? WHERE id_tanaman = ?", nama, idLahan, id)) {
                Util.pesan("Data berhasil diubah.");
                muatData();
                bersihkan();
            }
        } catch (IllegalArgumentException ex) {
            Util.pesan(ex.getMessage());
        }
    }
 
    private void hapus() {
        if (!Util.adaPilihan(txtIdTanaman.getText())) {
            return;
        }
        if (Util.konfirmasi("Hapus data tanaman ini?")
                && Util.eksekusi("DELETE FROM tanaman WHERE id_tanaman = ?", Integer.parseInt(txtIdTanaman.getText().trim()))) {
            Util.pesan("Data berhasil dihapus.");
            muatData();
            bersihkan();
        }
    }

